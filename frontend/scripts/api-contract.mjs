// The API contract: backend Pydantic models -> OpenAPI -> TypeScript types.
//
//   node scripts/api-contract.mjs           exit 1 if the generated types are stale
//   node scripts/api-contract.mjs --write   regenerate them (npm run api:gen)
//
// The schema comes from `backend/scripts/openapi.py`, run through uv, and is
// converted with the openapi-typescript Node API. Never edit the output.

import { spawnSync } from 'node:child_process'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const frontendDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const backendDir = resolve(frontendDir, '../backend')
// API_CONTRACT_TARGET overrides the output path (used by the drift test).
const target = resolve(
  frontendDir,
  process.env.API_CONTRACT_TARGET || 'src/api/generated/schema.d.ts',
)
const inside = !relative(frontendDir, target).startsWith('..')
const shown = inside ? relative(frontendDir, target) : target

const HEADER = `// Generated by scripts/api-contract.mjs from the backend OpenAPI schema.
// Do not edit: change the Pydantic models, then run \`npm run api:gen\`.

`

function dumpSchema() {
  const result = spawnSync(
    'uv',
    ['run', '--project', backendDir, 'python', resolve(backendDir, 'scripts/openapi.py')],
    { cwd: backendDir, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  )
  if (result.error) throw new Error(`can't run uv: ${result.error.message}`)
  if (result.status !== 0) {
    process.stderr.write(result.stderr)
    throw new Error(`backend/scripts/openapi.py exited with ${result.status}`)
  }
  return JSON.parse(result.stdout)
}

async function generate() {
  // A field with a default stays optional: `ids?` may be absent on the wire.
  const ast = await openapiTS(dumpSchema(), { defaultNonNullable: false })
  return HEADER + astToString(ast)
}

async function main() {
  const write = process.argv.includes('--write')
  const fresh = await generate()
  if (write) {
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, fresh)
    console.log(`api-contract: wrote ${shown}`)
    return 0
  }
  let current = null
  try {
    current = await readFile(target, 'utf8')
  } catch {
    // Missing counts as stale.
  }
  if (current !== fresh) {
    console.error(
      `api-contract: ${shown} is out of date with the backend models. ` +
        'Run `npm run api:gen` and commit the result.',
    )
    return 1
  }
  console.log(`api-contract: ${shown} is up to date`)
  return 0
}

main().then(
  (code) => process.exit(code),
  (error) => {
    console.error(`api-contract: ${error.message}`)
    process.exit(1)
  },
)
